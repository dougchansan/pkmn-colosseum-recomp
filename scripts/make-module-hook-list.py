"""Write the hook list the launcher's module build uses (moderngekko-port --hook-list).

One "ADDRESS SIZE [r]" line per guest function that a bundled mod hooks or patches
(RECOMP_HOOK / RECOMP_HOOK_RETURN / RECOMP_PATCH / RECOMP_FORCE_PATCH), sized from the
function table; "r" marks return hooks. The same set make-hook-aware-module.py builds from
--mods, so a module built on a player's machine is hook-aware for every bundled mod.

Usage: make-module-hook-list.py --functions patches/GC6E01-functions.csv --mods mods
           --output patches/GC6E01-module-hooks.txt
"""
import argparse
import re
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument('--functions', type=Path, required=True)
ap.add_argument('--mods', type=Path, action='append', required=True)
ap.add_argument('--output', type=Path, required=True)
a = ap.parse_args()

sizes = {}
for line in a.functions.read_text().splitlines():
    m = re.match(r'\s*(?:0x)?([0-9A-Fa-f]{8})\s*,\s*(?:0x)?([0-9A-Fa-f]+)', line)
    if m:
        sizes[int(m.group(1), 16)] = int(m.group(2), 16)

requested = {}
mod_hook = re.compile(r'RECOMP_(HOOK_RETURN|HOOK|FORCE_PATCH|PATCH)\(\s*0x([0-9A-Fa-f]{8})u?\s*,')
for directory in a.mods:
    for source in sorted(directory.glob('*.c')):
        if "hook-scan: skip" in source.read_text(errors="replace"):
            continue  # not built for this DOL; see the marker comment
        for kind, addr in mod_hook.findall(source.read_text(errors='replace')):
            addr = int(addr, 16)
            requested[addr] = requested.get(addr, False) or kind == 'HOOK_RETURN'

lines = ['# Generated by scripts/make-module-hook-list.py from the bundled mods -- do not edit.',
         '# ADDRESS SIZE [r]   (r = the function has return hooks)']
for addr in sorted(requested):
    if addr not in sizes:
        raise SystemExit(f'no function starts at {addr:08X} (hook or patch address)')
    lines.append(f'{addr:08X} {sizes[addr]:X}' + (' r' if requested[addr] else ''))
a.output.write_text('\n'.join(lines) + '\n')
print(f'{a.output}: {len(requested)} hooks')
